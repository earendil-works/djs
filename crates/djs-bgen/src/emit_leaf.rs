//! The leaf backend (D3260): a builtin tagged `@rust` becomes straight-line Rust in
//! `crates/djs-core/src/builtins/gen/leaves.rs`, with no frame and no state machine. The
//! helpers it calls are inlined; leaf intrinsics are called directly (the common ones
//! typed, the rest through the pure-leaf dispatch).
//!
//! User code may run at two kinds of place only, the conversion sites: `ToPrimitive` of an
//! object and `Get` (which may call a getter). At a site the function returns
//! `Fault::convert`: the interpreter runs the operation as bytecode (`%ToPrimitive`,
//! `%GetSite`) and calls the builtin again with the result in the site's shadow slot.
//! Everything before a site is pure (leaf intrinsics that change nothing), so running it
//! again is unobservable, and arguments are never replaced, so checks of the original
//! values (`this === null`) see what the bytecode would.
//!
//! Eligible bodies (else bgen fails): no loops, `try`, `break`, rest parameters or other
//! reentrant intrinsics; at most four sites. `throw New*Error("literal")` becomes an error
//! raised with the builtin as its innermost (native) stack frame. Builtins whose bodies
//! differ only in leaf ids and number literals share one function (`d.ids[k]`,
//! `d.lits[k]`).

use std::collections::{BTreeSet, HashMap};

use crate::ast::{AssignOp, BinOp, Expr, ExprKind, Stmt, Type, UnOp};
use crate::check::{Callee, Program};

/// How a value is held in the generated Rust.
#[derive(Clone, Copy, PartialEq, Debug)]
enum Rt {
    Val,
    Num,
    Bool,
}

fn rt(t: Type) -> Rt {
    match t {
        Type::F64 | Type::I32 | Type::U32 | Type::IntLit(_) | Type::NumLit => Rt::Num,
        Type::Bool => Rt::Bool,
        _ => Rt::Val,
    }
}

fn rust_ty(r: Rt) -> &'static str {
    match r {
        Rt::Val => "Value",
        Rt::Num => "f64",
        Rt::Bool => "bool",
    }
}

fn conv(code: String, from: Rt, to: Rt) -> String {
    match (from, to) {
        _ if from == to => code,
        (Rt::Num, Rt::Val) => format!("lnum({code})"),
        (Rt::Bool, Rt::Val) => format!("Value::bool({code})"),
        (Rt::Val, Rt::Num) => format!("f64_of({code})"),
        (Rt::Val, Rt::Bool) => format!("({code}).as_bool() == Some(true)"),
        _ => panic!("bgen checked the types"),
    }
}

struct E<'a> {
    p: &'a Program,
    vars: HashMap<String, (String, Rt)>,
    next: u32,
    sites: u32,
    pids: Vec<String>,
    /// Intrinsic ids used as constants (the conversion sites' operations).
    consts: BTreeSet<String>,
    plits: Vec<String>,
    /// The inlined helpers being emitted: the label to break to and the return type.
    exits: Vec<(String, Rt)>,
    inlining: Vec<usize>,
}

/// The `@rust` builtins as Rust (leaves.rs), or the reason one is not eligible.
pub fn emit(p: &Program) -> Result<String, String> {
    let mut ids = BTreeSet::new();
    let mut table: Vec<(String, usize, Vec<String>, Vec<String>)> = Vec::new();
    let mut shapes: Vec<String> = Vec::new();
    for bi in p.builtins.iter().filter(|b| b.rust) {
        let mut e = E::new(p);
        let body = e
            .builtin(p.function(bi))
            .map_err(|m| format!("djs-bgen: @rust {}: {m}", bi.name))?;
        if e.sites > 4 {
            return Err(format!(
                "djs-bgen: @rust {}: more than 4 conversions",
                bi.name
            ));
        }
        let shape = match shapes.iter().position(|s| *s == body) {
            Some(i) => i,
            None => {
                shapes.push(body);
                shapes.len() - 1
            }
        };
        ids.extend(e.pids.iter().cloned());
        ids.extend(e.consts.iter().cloned());
        table.push((bi.name.clone(), shape, e.pids, e.plits));
    }
    let mut out = String::from(
        "// Generated by djs-bgen (leaf backend, D3260) from builtins/*.ts. Do not edit.\n\n\
         use crate::builtins::fast::{Leaf, LeafData, Shadow};\n\
         use crate::heap::atoms;\n\
         use crate::interp::ErrorKind;\n\
         use crate::interp::conv::Fault;\n\
         use crate::interp::run::Exec;\n\
         use crate::interp::run::lnum;\n\
         use crate::interp::run::native::{f64_of, iid};\n\
         use crate::value::Value;\n\
         use alloc::string::String;\n\n",
    );
    for id in &ids {
        out.push_str(&format!("const I_{}: u16 = iid(\"{id}\");\n", upper(id)));
    }
    out.push_str("\n/// The generated builtins (`%MarkFast` finds them after `FAST`).\n");
    out.push_str("pub(crate) static LEAVES: &[Leaf] = &[\n");
    for (n, shape, ids, lits) in &table {
        let ids: Vec<String> = ids.iter().map(|i| format!("I_{}", upper(i))).collect();
        out.push_str(&format!(
            "    Leaf {{ run: shape_{shape}, data: LeafData {{ ids: &[{}], lits: &[{}] }} }}, // {n}\n",
            ids.join(", "),
            lits.join(", ")
        ));
    }
    out.push_str("];\n\n#[cfg(djs_prelude)]\npub(crate) static LEAF_NAMES: &[&str] = &[\n");
    for (n, ..) in &table {
        out.push_str(&format!("    \"{n}\",\n"));
    }
    out.push_str("];\n\n");
    for (i, body) in shapes.iter().enumerate() {
        let users: Vec<&str> = table
            .iter()
            .filter(|t| t.1 == i)
            .map(|t| t.0.as_str())
            .collect();
        out.push_str(&format!(
            "// {}\nfn shape_{i}(ex: &mut Exec<'_>, this: Value, args: &[Value], sh: &Shadow, d: &LeafData) -> Result<Value, Fault> {{\n{body}}}\n\n",
            users.join(", ")
        ));
    }
    Ok(out)
}

fn upper(name: &str) -> String {
    let mut s = String::new();
    for (i, c) in name.chars().enumerate() {
        if c.is_uppercase() && i > 0 {
            s.push('_');
        }
        s.push(c.to_ascii_uppercase());
    }
    s
}

fn rust_str(units: &[u16]) -> Option<String> {
    let s = String::from_utf16(units).ok()?;
    Some(format!("{s:?}"))
}

impl<'a> E<'a> {
    fn new(p: &'a Program) -> E<'a> {
        E {
            p,
            vars: HashMap::new(),
            next: 0,
            sites: 0,
            pids: Vec::new(),
            consts: BTreeSet::new(),
            plits: Vec::new(),
            exits: Vec::new(),
            inlining: Vec::new(),
        }
    }

    fn fresh(&mut self, base: &str) -> String {
        self.next += 1;
        format!("{base}{}", self.next)
    }

    fn builtin(&mut self, f: &crate::ast::Function) -> Result<String, String> {
        let mut pre = String::new();
        for (i, prm) in f.params.iter().enumerate() {
            if prm.rest {
                return Err("rest parameter".into());
            }
            let n = format!("a_{}", prm.name);
            let r = rt(prm.ty.ty);
            pre.push_str(&format!(
                "    let {n}: {} = {};\n",
                rust_ty(r),
                conv(
                    format!("args.get({i}).copied().unwrap_or(Value::UNDEFINED)"),
                    Rt::Val,
                    r
                )
            ));
            self.vars.insert(prm.name.clone(), (n, r));
        }
        let body = self.stmts(&f.body.stmts, 1)?;
        Ok(format!(
            "{pre}{body}    Err(Exec::l_error(ErrorKind::InternalError, \"fell through\"))\n"
        ))
    }

    fn stmts(&mut self, ss: &[Stmt], ind: usize) -> Result<String, String> {
        let mut out = String::new();
        for s in ss {
            out.push_str(&self.stmt(s, ind)?);
        }
        Ok(out)
    }

    fn stmt(&mut self, s: &Stmt, ind: usize) -> Result<String, String> {
        let pad = "    ".repeat(ind);
        Ok(match s {
            Stmt::Decl { name, ty, init, .. } => {
                let r = rt(ty.ty);
                let (c, cr) = self.expr(init)?;
                let n = self.fresh(&format!("l_{name}_"));
                let line = format!("{pad}let mut {n}: {} = {};\n", rust_ty(r), conv(c, cr, r));
                self.vars.insert(name.clone(), (n, r));
                line
            }
            Stmt::Assign {
                target, op, value, ..
            } => {
                let (n, r) = self.var(target)?;
                let (c, cr) = self.expr(value)?;
                let c = conv(c, cr, r);
                match op {
                    AssignOp::Assign => format!("{pad}{n} = {c};\n"),
                    AssignOp::Add if r == Rt::Val => {
                        format!("{pad}{{ let b = {c}; {n} = ex.n_concat({n}, b)?; }}\n")
                    }
                    op => {
                        let e =
                            self.arith(op.binary().unwrap(), (n.clone(), Rt::Num), (c, Rt::Num))?;
                        format!("{pad}{n} = {};\n", e.0)
                    }
                }
            }
            Stmt::Update { target, inc, .. } => {
                let (n, _) = self.var(target)?;
                format!("{pad}{n} {}= 1.0;\n", if *inc { "+" } else { "-" })
            }
            Stmt::Expr(e) => {
                let (c, _) = self.expr(e)?;
                format!("{pad}let _ = {c};\n")
            }
            Stmt::If {
                cond, then, els, ..
            } => {
                let (c, cr) = self.expr(cond)?;
                let c = conv(c, cr, Rt::Bool);
                let a = self.stmt(then, ind + 1)?;
                match els {
                    Some(e) => {
                        let b = self.stmt(e, ind + 1)?;
                        format!("{pad}if {c} {{\n{a}{pad}}} else {{\n{b}{pad}}}\n")
                    }
                    None => format!("{pad}if {c} {{\n{a}{pad}}}\n"),
                }
            }
            Stmt::Return { value, .. } => {
                let v = match value {
                    Some(v) => Some(self.expr(v)?),
                    None => None,
                };
                if let Some((label, r)) = self.exits.last().cloned() {
                    let v = v.map_or_else(
                        || conv("Value::UNDEFINED".into(), Rt::Val, r),
                        |(c, cr)| conv(c, cr, r),
                    );
                    format!("{pad}break '{label} ({v});\n")
                } else {
                    let v = v.map_or("Value::UNDEFINED".into(), |(c, r)| conv(c, r, Rt::Val));
                    format!("{pad}return Ok({v});\n")
                }
            }
            Stmt::Throw { value, .. } => format!("{pad}return Err({});\n", self.throw(value)?),
            Stmt::Block(b) => self.stmts(&b.stmts, ind)?,
            Stmt::While { .. } | Stmt::DoWhile { .. } | Stmt::For { .. } => {
                return Err("loop".into());
            }
            Stmt::Try { .. } => return Err("try".into()),
            Stmt::Break(_) | Stmt::Continue(_) => return Err("break/continue".into()),
        })
    }

    /// The fault for `throw value`: an error made from a literal message is thrown with
    /// the builtin's native frame (as its bytecode frame would be in the stack).
    fn throw(&mut self, value: &Expr) -> Result<String, String> {
        if let ExprKind::Call { callee, args, .. } = &value.kind {
            let kind = match callee.as_str() {
                "NewTypeError" => Some("TypeError"),
                "NewRangeError" => Some("RangeError"),
                "NewSyntaxError" => Some("SyntaxError"),
                _ => None,
            };
            if let (Some(k), [m]) = (kind, args.as_slice())
                && let ExprKind::Str(units) = &m.kind
            {
                let s = rust_str(units).ok_or("message")?;
                return Ok(format!("Exec::l_error(ErrorKind::{k}, {s})"));
            }
        }
        let (c, r) = self.expr(value)?;
        Ok(format!("Fault::throw({})", conv(c, r, Rt::Val)))
    }

    fn var(&self, name: &str) -> Result<(String, Rt), String> {
        self.vars
            .get(name)
            .cloned()
            .ok_or_else(|| format!("unknown variable {name}"))
    }

    fn arith(&self, op: BinOp, a: (String, Rt), b: (String, Rt)) -> Result<(String, Rt), String> {
        let (x, y) = (conv(a.0, a.1, Rt::Num), conv(b.0, b.1, Rt::Num));
        let i = |e: &str| format!("(({e}) as i32)");
        Ok(match op {
            BinOp::Add => (format!("({x} + {y})"), Rt::Num),
            BinOp::Sub => (format!("({x} - {y})"), Rt::Num),
            BinOp::Mul => (format!("({x} * {y})"), Rt::Num),
            BinOp::Div => (format!("({x} / {y})"), Rt::Num),
            BinOp::Rem => (format!("({x} % {y})"), Rt::Num),
            BinOp::BitAnd => (format!("(({} & {}) as f64)", i(&x), i(&y)), Rt::Num),
            BinOp::BitOr => (format!("(({} | {}) as f64)", i(&x), i(&y)), Rt::Num),
            BinOp::BitXor => (format!("(({} ^ {}) as f64)", i(&x), i(&y)), Rt::Num),
            BinOp::Shl => (
                format!("({}.wrapping_shl({} as u32) as f64)", i(&x), i(&y)),
                Rt::Num,
            ),
            BinOp::Shr => (
                format!("({}.wrapping_shr({} as u32) as f64)", i(&x), i(&y)),
                Rt::Num,
            ),
            BinOp::UShr => (
                format!("(({} as u32).wrapping_shr({} as u32) as f64)", i(&x), i(&y)),
                Rt::Num,
            ),
            BinOp::Lt => (format!("({x} < {y})"), Rt::Bool),
            BinOp::Le => (format!("({x} <= {y})"), Rt::Bool),
            BinOp::Gt => (format!("({x} > {y})"), Rt::Bool),
            BinOp::Ge => (format!("({x} >= {y})"), Rt::Bool),
            _ => return Err(format!("operator {}", op.as_str())),
        })
    }

    /// A number literal: a parameter of the shape.
    fn num_lit(&mut self, text: String) -> String {
        self.plits.push(text);
        format!("d.lits[{}]", self.plits.len() - 1)
    }

    /// A leaf intrinsic's id: a parameter of the shape.
    fn leaf_id(&mut self, name: &str) -> String {
        self.pids.push(name.to_string());
        format!("d.ids[{}]", self.pids.len() - 1)
    }

    fn expr(&mut self, e: &Expr) -> Result<(String, Rt), String> {
        Ok(match &e.kind {
            ExprKind::Ident(n) => self.var(n)?,
            ExprKind::This => ("this".into(), Rt::Val),
            ExprKind::Undefined => ("Value::UNDEFINED".into(), Rt::Val),
            ExprKind::Null => ("Value::NULL".into(), Rt::Val),
            ExprKind::Bool(b) => {
                let lit = self.num_lit(if *b { "1.0" } else { "0.0" }.into());
                (format!("({lit} != 0.0)"), Rt::Bool)
            }
            ExprKind::Num(v, _) => (self.num_lit(format!("{v:?}")), Rt::Num),
            ExprKind::Str(units) => {
                let s = rust_str(units).ok_or("string literal")?;
                (format!("ex.l_str({s})?"), Rt::Val)
            }
            ExprKind::Paren(x) => self.expr(x)?,
            ExprKind::NewTarget => ("Value::UNDEFINED".into(), Rt::Val),
            ExprKind::Unary(op, x) => {
                let (c, r) = self.expr(x)?;
                match op {
                    UnOp::Not => (format!("!({})", conv(c, r, Rt::Bool)), Rt::Bool),
                    UnOp::Neg => (format!("(-{})", conv(c, r, Rt::Num)), Rt::Num),
                    UnOp::BitNot => (
                        format!("((!({} as i32)) as f64)", conv(c, r, Rt::Num)),
                        Rt::Num,
                    ),
                }
            }
            ExprKind::Binary(op, a, b) => {
                let x = self.expr(a)?;
                let y = self.expr(b)?;
                match op {
                    BinOp::And | BinOp::Or => {
                        let o = if *op == BinOp::And { "&&" } else { "||" };
                        (
                            format!(
                                "({} {o} {})",
                                conv(x.0, x.1, Rt::Bool),
                                conv(y.0, y.1, Rt::Bool)
                            ),
                            Rt::Bool,
                        )
                    }
                    BinOp::StrictEq | BinOp::StrictNe => {
                        let eq = self.strict_eq(a, b, x, y);
                        if *op == BinOp::StrictEq {
                            (eq, Rt::Bool)
                        } else {
                            (format!("!{eq}"), Rt::Bool)
                        }
                    }
                    BinOp::Add if x.1 == Rt::Val || y.1 == Rt::Val => (
                        format!(
                            "{{ let a = {}; let b = {}; ex.n_concat(a, b)? }}",
                            conv(x.0, x.1, Rt::Val),
                            conv(y.0, y.1, Rt::Val)
                        ),
                        Rt::Val,
                    ),
                    op => self.arith(*op, x, y)?,
                }
            }
            ExprKind::Cond(c, a, b) => {
                let (cc, cr) = self.expr(c)?;
                let (ac, ar) = self.expr(a)?;
                let (bc, br) = self.expr(b)?;
                let r = if ar == br { ar } else { Rt::Val };
                (
                    format!(
                        "(if {} {{ {} }} else {{ {} }})",
                        conv(cc, cr, Rt::Bool),
                        conv(ac, ar, r),
                        conv(bc, br, r)
                    ),
                    r,
                )
            }
            ExprKind::Call { callee, args, .. } => self.call(callee, args)?,
        })
    }

    fn strict_eq(&mut self, a: &Expr, b: &Expr, x: (String, Rt), y: (String, Rt)) -> String {
        let lit = |e: &Expr| match e.kind {
            ExprKind::Undefined => Some("is_undefined"),
            ExprKind::Null => Some("is_null"),
            _ => None,
        };
        if let Some(m) = lit(b) {
            return format!("({}).{m}()", conv(x.0, x.1, Rt::Val));
        }
        if let Some(m) = lit(a) {
            return format!("({}).{m}()", conv(y.0, y.1, Rt::Val));
        }
        match (x.1, y.1) {
            (Rt::Num, Rt::Num) | (Rt::Bool, Rt::Bool) => format!("({} == {})", x.0, y.0),
            _ => format!(
                "{{ let a = {}; let b = {}; ex.n_strict_eq(a, b) }}",
                conv(x.0, x.1, Rt::Val),
                conv(y.0, y.1, Rt::Val)
            ),
        }
    }

    fn call(&mut self, callee: &str, args: &[Expr]) -> Result<(String, Rt), String> {
        let p = self.p;
        let (kind, sig) = p
            .callees
            .get(callee)
            .ok_or_else(|| format!("unknown callee {callee}"))?;
        match kind {
            Callee::Intrinsic { reentrant: true } if callee == "Get" => self.get_site(args),
            Callee::Intrinsic { reentrant: true } => Err(format!("reentrant %{callee}")),
            Callee::Intrinsic { .. } => self.leaf(callee, sig, args),
            Callee::Builtin(_) if callee == "ToPrimitive" => self.primitive_site(args),
            // ToString and ToNumber (conversion.ts) as one call each: the primitive case
            // inline, the object's site and the conversion out of line.
            // IsRegExp (string.ts): its Get of @@match is a site; out of line for objects.
            Callee::Builtin(_) if callee == "IsRegExp" => {
                let [v] = args else {
                    return Err("IsRegExp arity".into());
                };
                let (c, r) = self.expr(v)?;
                let v = conv(c, r, Rt::Val);
                let k = self.sites;
                self.sites += 1;
                Ok((
                    format!(
                        "{{ let a = {v}; a.as_object().is_some() && ex.l_is_regexp_site(a, sh, {k})? }}"
                    ),
                    Rt::Bool,
                ))
            }
            Callee::Builtin(_) if callee == "ToString" || callee == "ToNumber" => {
                let [v] = args else {
                    return Err(format!("{callee} arity"));
                };
                let (c, r) = self.expr(v)?;
                let v = conv(c, r, Rt::Val);
                let k = self.sites;
                self.sites += 1;
                Ok(if callee == "ToString" {
                    (format!("ex.l_to_string_at({v}, sh, {k})?"), Rt::Val)
                } else {
                    (format!("ex.l_to_number_at({v}, sh, {k})?"), Rt::Num)
                })
            }
            Callee::Builtin(b) => self.inline(*b, args),
        }
    }

    /// A helper's body as a labeled block in this function; its parameters bound to the
    /// arguments (evaluated in order).
    fn inline(&mut self, b: usize, args: &[Expr]) -> Result<(String, Rt), String> {
        let p = self.p;
        let f = p.function(&p.builtins[b]);
        if f.this_ty.is_some() || f.params.iter().any(|q| q.rest) {
            return Err(format!("helper {} with this or rest", f.name));
        }
        if self.inlining.contains(&b) || self.inlining.len() > 8 {
            return Err(format!("recursive helper {}", f.name));
        }
        let mut pre = String::new();
        let mut bound = Vec::new();
        for (i, prm) in f.params.iter().enumerate() {
            let r = rt(prm.ty.ty);
            let v = match args.get(i) {
                Some(a) => {
                    let (c, cr) = self.expr(a)?;
                    conv(c, cr, r)
                }
                None => conv("Value::UNDEFINED".into(), Rt::Val, r),
            };
            let n = self.fresh(&format!("p_{}_", prm.name));
            pre.push_str(&format!("let mut {n}: {} = {v}; ", rust_ty(r)));
            bound.push((prm.name.clone(), (n, r)));
        }
        let saved = std::mem::take(&mut self.vars);
        self.vars.extend(bound);
        let label = self.fresh("b");
        let ret = rt(f.ret.ty);
        self.exits.push((label.clone(), ret));
        self.inlining.push(b);
        let body = self.stmts(&f.body.stmts, 2);
        self.inlining.pop();
        self.exits.pop();
        self.vars = saved;
        let body = body.map_err(|m| format!("{}: {m}", f.name))?;
        Ok((
            format!("('{label}: {{ {pre}\n{body}        unreachable!() }})"),
            ret,
        ))
    }

    fn leaf(
        &mut self,
        callee: &str,
        sig: &crate::check::Sig,
        args: &[Expr],
    ) -> Result<(String, Rt), String> {
        let mut vals = Vec::new();
        for (i, a) in args.iter().enumerate() {
            let (c, r) = self.expr(a)?;
            let want = sig.params.get(i).map_or(Rt::Val, |(t, _)| rt(*t));
            vals.push((conv(c, r, want), want));
        }
        let ret = rt(sig.ret);
        let one = |i: usize| vals.get(i).map(|v| v.0.clone()).unwrap_or_default();
        // Type tests and casts inline.
        let inline = match callee {
            "IsObject" => Some((format!("({}).as_object().is_some()", one(0)), Rt::Bool)),
            "IsString" => Some((format!("({}).as_string().is_some()", one(0)), Rt::Bool)),
            "IsNumber" => Some((format!("({}).is_number()", one(0)), Rt::Bool)),
            "IsSymbol" => Some((format!("({}).as_symbol().is_some()", one(0)), Rt::Bool)),
            "IsBoolean" => Some((format!("({}).as_bool().is_some()", one(0)), Rt::Bool)),
            "AsStr" | "AsObj" | "AsSym" | "AsBool" => Some((one(0), Rt::Val)),
            "AsNumber" => Some((format!("f64_of({})", one(0)), Rt::Num)),
            "ArgumentCount" => Some(("(args.len() as f64)".into(), Rt::Num)),
            "ToNumberPrimitive" => Some((format!("ex.l_to_number({})?", one(0)), Rt::Num)),
            "ToStringPrimitive" => Some((format!("ex.l_to_string({})?", one(0)), Rt::Val)),
            _ => None,
        };
        if let Some((c, r)) = inline {
            return Ok((conv(c, r, ret), ret));
        }
        // Typed leaves: called directly, no dispatch.
        let v = |i: usize| conv(one(i), vals.get(i).map_or(Rt::Val, |x| x.1), Rt::Val);
        let n = |i: usize| conv(one(i), vals.get(i).map_or(Rt::Num, |x| x.1), Rt::Num);
        let typed: Option<(String, Rt)> = match callee {
            c if c.starts_with("F64") && c != "F64ToU32" && c != "F64ToI32" => {
                let y = if vals.len() > 1 {
                    n(1)
                } else {
                    "f64::NAN".into()
                };
                let (x, id) = (n(0), self.leaf_id(callee));
                Some((format!("Exec::l_math({id}, {x}, {y})"), Rt::Num))
            }
            "ToIntegerOrInfinityNumber" => Some((format!("Exec::l_integer({})", n(0)), Rt::Num)),
            "StrLength" => Some((format!("ex.l_str_len({})", v(0)), Rt::Num)),
            "StrCharCodeAt" => Some((
                format!(
                    "{{ let s = {}; let k = {}; ex.l_char_code_at(s, k)? }}",
                    v(0),
                    n(1)
                ),
                Rt::Val,
            )),
            "StrSubstring" => Some((
                format!(
                    "{{ let s = {}; let a = {}; let b = {}; ex.l_substring(s, a, b)? }}",
                    v(0),
                    v(1),
                    v(2)
                ),
                Rt::Val,
            )),
            "StrIndexOf" | "StrLastIndexOf" => Some((
                format!(
                    "{{ let s = {}; let t = {}; let f = {}; ex.l_index_of(s, t, f, {})? }}",
                    v(0),
                    v(1),
                    v(2),
                    callee == "StrLastIndexOf"
                ),
                Rt::Num,
            )),
            "StrTrim" => Some((
                format!("{{ let s = {}; let w = {}; ex.l_trim(s, w)? }}", v(0), v(1)),
                Rt::Val,
            )),
            "StrToCase" => Some((
                format!("{{ let s = {}; let u = {}; ex.l_case(s, u)? }}", v(0), v(1)),
                Rt::Val,
            )),
            "StrPad" => Some((
                format!(
                    "{{ let s = {}; let f = {}; let k = {}; let a = {}; ex.l_pad(s, f, k, a)? }}",
                    v(0),
                    v(1),
                    n(2),
                    conv(one(3), vals.get(3).map_or(Rt::Bool, |x| x.1), Rt::Bool)
                ),
                Rt::Val,
            )),
            "StrRepeat" => Some((
                format!(
                    "{{ let s = {}; let k = {}; ex.l_repeat(s, k)? }}",
                    v(0),
                    v(1)
                ),
                Rt::Val,
            )),
            "NumberToString" | "NumberToFixed" | "NumberToExponential" | "NumberToPrecision" => {
                let op = match callee {
                    "NumberToString" => 0,
                    "NumberToFixed" => 1,
                    "NumberToExponential" => 2,
                    _ => 3,
                };
                Some((
                    format!(
                        "{{ let x = {}; let a = {}; ex.l_num_format({op}, x, a)? }}",
                        n(0),
                        v(1)
                    ),
                    Rt::Val,
                ))
            }
            _ => None,
        };
        if let Some((c, r)) = typed {
            return Ok((conv(c, r, ret), ret));
        }
        if vals.len() > 3 {
            return Err(format!("%{callee} with more than 3 arguments"));
        }
        let mut a: Vec<String> = vals.into_iter().map(|(c, r)| conv(c, r, Rt::Val)).collect();
        let count = a.len();
        while a.len() < 3 {
            a.push("Value::UNDEFINED".into());
        }
        let id = self.leaf_id(callee);
        let c = format!(
            "{{ let a = [{}]; ex.l_leaf({id}, a, {count})? }}",
            a.join(", ")
        );
        Ok((conv(c, Rt::Val, ret), ret))
    }

    /// A conversion site: `fast` may answer without the interpreter; else the value from
    /// the shadow slot if the interpreter has run the operation, else the request to run
    /// `%op(a, b)` (`b` is pure and evaluated only for the request).
    fn site(&mut self, op: &str, a: String, b: String, fast: Option<&str>) -> String {
        let k = self.sites;
        self.sites += 1;
        let fast = fast.map_or(String::new(), |f| format!("if {f} {{ a }} else "));
        format!(
            "{{ let a = {a}; {fast}if sh.mask & {} != 0 {{ sh.vals[{k}] }} else {{ let b = {b}; return Err(Fault::convert({k}, I_{}, a, b)) }} }}",
            1u32 << k,
            upper(op)
        )
    }

    /// `ToPrimitive(v, hint)`: a primitive is itself; an object's primitive comes from
    /// the site.
    fn primitive_site(&mut self, args: &[Expr]) -> Result<(String, Rt), String> {
        let [v, hint] = args else {
            return Err("ToPrimitive arity".into());
        };
        let hint = match &hint.kind {
            ExprKind::Str(u) => rust_str(u).ok_or("hint")?,
            _ => return Err("ToPrimitive hint not a literal".into()),
        };
        let (c, r) = self.expr(v)?;
        let v = conv(c, r, Rt::Val);
        // The request is built out of line (`l_primitive_site`): one call per site.
        let k = self.sites;
        self.sites += 1;
        Ok((
            format!(
                "{{ let a = {v}; if a.as_object().is_none() {{ a }} else if sh.mask & {} != 0 {{ sh.vals[{k}] }} else {{ return Err(ex.l_primitive_site({k}, a, {hint})) }} }}",
                1u32 << k
            ),
            Rt::Val,
        ))
    }

    /// `Get(o, key)`: always a site (it may call a getter); `%GetSite` runs it.
    fn get_site(&mut self, args: &[Expr]) -> Result<(String, Rt), String> {
        let [o, key] = args else {
            return Err("Get arity".into());
        };
        let (oc, or) = self.expr(o)?;
        let (kc, kr) = self.expr(key)?;
        self.consts.insert("GetSite".into());
        Ok((
            self.site(
                "GetSite",
                conv(oc, or, Rt::Val),
                conv(kc, kr, Rt::Val),
                None,
            ),
            Rt::Val,
        ))
    }
}
