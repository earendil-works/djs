#!/usr/bin/env python3
"""Generate crates/djs-core/src/unicode/tables.rs from the Unicode Character Database.

The UCD files are downloaded once into vendor/unicode/<version>/ of the primary checkout
(shared by all worktrees, gitignored). The generated Rust file is checked in.

The Unicode version matches what test262 at the pinned commit expects (the version
dquickts uses, see its unicode_download.sh).

Usage: scripts/gen-unicode.py [--check]
  --check   do not write, exit 1 if the checked-in table is out of date
"""

import os
import subprocess
import sys

UNICODE_VERSION = "17.0.0"
BASE_URL = f"https://www.unicode.org/Public/{UNICODE_VERSION}/ucd"
FILES = ["DerivedCoreProperties.txt", "extracted/DerivedGeneralCategory.txt"]

# Packed range encoding: start << LEN_BITS | (len - 1). start needs 21 bits.
LEN_BITS = 11
MAX_LEN = 1 << LEN_BITS

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT = os.path.join(ROOT, "crates/djs-core/src/unicode/tables.rs")


def primary_checkout():
    common = subprocess.check_output(
        ["git", "rev-parse", "--path-format=absolute", "--git-common-dir"],
        cwd=ROOT,
        text=True,
    ).strip()
    return os.path.dirname(common)


def fetch(vendor_dir, name):
    path = os.path.join(vendor_dir, name)
    if os.path.exists(path):
        return path
    os.makedirs(os.path.dirname(path), exist_ok=True)
    url = f"{BASE_URL}/{name}"
    tmp = path + ".tmp"
    # curl rather than urllib: it uses the system certificate store. unicode.org
    # occasionally answers with transient 5xx errors, hence the retries.
    cmd = ["curl", "-fsSL", "--retry", "5", "--retry-all-errors", "-o", tmp, url]
    if subprocess.call(cmd) != 0:
        sys.exit(f"failed to download {url}")
    os.replace(tmp, path)
    return path


def parse_ucd(path, wanted):
    """Return {property: set(code points)} for the wanted property values."""
    out = {w: set() for w in wanted}
    with open(path, encoding="utf-8") as f:
        first = f.readline()
        if UNICODE_VERSION not in first:
            sys.exit(f"{path}: expected Unicode {UNICODE_VERSION}, got {first.strip()}")
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            fields = [x.strip() for x in line.split(";")]
            prop = fields[1]
            if prop not in out:
                continue
            lo, _, hi = fields[0].partition("..")
            lo = int(lo, 16)
            hi = int(hi, 16) if hi else lo
            out[prop].update(range(lo, hi + 1))
    return out


def ranges(cps):
    out = []
    for c in sorted(cps):
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


def packed(cps):
    words = []
    for lo, hi in ranges(cps):
        while lo <= hi:
            n = min(hi - lo + 1, MAX_LEN)
            words.append((lo << LEN_BITS) | (n - 1))
            lo += n
    return words


def emit_table(name, doc, words):
    lines = [f"/// {doc}", f"pub(super) static {name}: [u32; {len(words)}] = ["]
    row = []
    for w in words:
        row.append(f"0x{w:08x},")
        if len(row) == 8:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines.append("];")
    return "\n".join(lines)


def generate():
    vendor = os.path.join(primary_checkout(), "vendor", "unicode", UNICODE_VERSION)
    core = parse_ucd(fetch(vendor, FILES[0]), ["ID_Start", "ID_Continue"])
    gc = parse_ucd(fetch(vendor, FILES[1]), ["Zs"])

    id_start = {c for c in core["ID_Start"] if c >= 0x80}
    id_continue = {c for c in core["ID_Continue"] if c >= 0x80}
    assert id_start <= id_continue, "ID_Start must be a subset of ID_Continue"
    continue_only = id_continue - id_start
    space = {c for c in gc["Zs"] if c >= 0x80}

    parts = [
        "// Generated by scripts/gen-unicode.py from the Unicode Character Database. Do not edit.",
        "//",
        "// Ranges are packed as `start << LEN_BITS | (len - 1)` and sorted by start. Only",
        "// code points >= 0x80 are listed; ASCII is handled by the callers.",
        "",
        f'pub const UNICODE_VERSION: &str = "{UNICODE_VERSION}";',
        "",
        f"pub(super) const LEN_BITS: u32 = {LEN_BITS};",
        "",
        emit_table("ID_START", "Non-ASCII `ID_Start`.", packed(id_start)),
        "",
        emit_table(
            "ID_CONTINUE_ONLY",
            "Non-ASCII `ID_Continue` code points that are not `ID_Start`.",
            packed(continue_only),
        ),
        "",
        emit_table("SPACE_SEPARATOR", "Non-ASCII `Space_Separator` (Zs).", packed(space)),
        "",
    ]
    return "\n".join(parts)


def main():
    text = generate()
    if "--check" in sys.argv[1:]:
        with open(OUT, encoding="utf-8") as f:
            if f.read() != text:
                sys.exit(f"{OUT} is out of date; run scripts/gen-unicode.py")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
