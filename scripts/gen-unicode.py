MODIFIERS = range(0x1F3FB, 0x1F400)
HAIR = range(0x1F9B0, 0x1F9B4)


def encode_partition(sets):
    """The code space as runs of the index of the set each code point is in (each code
    point in exactly one): `len << 5 | index` for lengths 1..=6, else `7 << 5 | index`
    and a varint length - 7."""
    owner = [None] * 0x110000
    for i, cps in enumerate(sets):
        for c in cps:
            assert owner[c] is None
            owner[c] = i
    assert all(o is not None for o in owner)
    out = []
    c = 0
    while c < 0x110000:
        j = c
        while j < 0x110000 and owner[j] == owner[c]:
            j += 1
        n = j - c
        if n <= 6:
            out.append(n << 5 | owner[c])
        else:
            out.append(7 << 5 | owner[c])
            varint(n - 7, out)
        c = j
    return out


def gc_mask_toward(target, base, leaf_sets):
    """The union of `base` and the General_Category leaves that bring it closer to
    `target` (more of the leaf's new code points inside than outside): (mask, union)."""
    mask, full = 0, set(base)
    for i, leaf in enumerate(leaf_sets):
        new = leaf - full
        if len(new & target) > len(new - target):
            mask |= 1 << i
            full |= leaf
    return mask, full


def zwj_pattern(n_mod, hair, variants):
    """The expansion code of a ZWJ template's variants (n_mod modifier slots, a hair slot
    or not): 0 none, 1 one slot of all five tones, 2 two slots of all 25 pairs, 3 two
    slots of the 20 pairs of different tones; +4 with all four hair components. None if
    the variants are none of these."""
    hairs = list(range(4)) if hair else [None]
    pairs = [(a, b) for a in range(5) for b in range(5)]
    options = {0: [()], 1: [(i,) for i in range(5)], 2: pairs,
               3: [(a, b) for a, b in pairs if a != b]}
    for code, mods in options.items():
        if len(mods[0]) != n_mod:
            continue
        if variants == {(m, h) for m in mods for h in hairs}:
            return code + (4 if hair else 0)
    return None


def encode_zwj(seqs):
    """ZWJ sequences as templates (D2334): a sequence with skin tone modifiers and hair
    components replaced by slots, and the code of the variants it stands for
    (zwj_pattern). Templates are sorted and front-coded: the count, then per template the
    shared prefix length, the number of new tokens, the variant code and the tokens:
    0 a modifier slot, 1 the hair slot, 2 U+200D, 3 U+FE0F, else 4 + the zigzag delta of
    a code point from the previous one (0 at the start)."""
    groups = {}
    for q in seqs:
        sk, mods, hair = [], [], None
        for c in q:
            if c in MODIFIERS:
                sk.append("M")
                mods.append(c - MODIFIERS[0])
            elif c in HAIR:
                sk.append("H")
                hair = c - HAIR[0]
            else:
                sk.append(c)
        groups.setdefault(tuple(sk), set()).add((tuple(mods), hair))
    special = {"M": 0, "H": 1, 0x200D: 2, 0xFE0F: 3}
    key = lambda sk: [x if isinstance(x, int) else -1 for x in sk]
    out = []
    varint(len(groups), out)
    prev = []
    for sk in sorted(groups, key=key):
        code = zwj_pattern(sk.count("M"), "H" in sk, groups[sk])
        assert code is not None, sk
        p = 0
        while p < len(sk) and p < len(prev) and sk[p] == prev[p]:
            p += 1
        varint(p, out)
        varint(len(sk) - p, out)
        out.append(code)
        last = next((x for x in reversed(sk[:p]) if x not in special), 0)
        for x in sk[p:]:
            if x in special:
                out.append(special[x])
            else:
                varint(4 + zigzag(x - last), out)
                last = x
        prev = list(sk)
    return out


def value_aliases(path, prop):
    """[[short, long, other aliases...]] of a property in PropertyValueAliases.txt."""
    check_version(path)
    out = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            fields = [x.strip() for x in line.split(";")]
            if fields[0] == prop:
                out.append(fields[1:])
    return out


def generate_props(vendor):
    data = []
    pva = fetch(vendor, "PropertyValueAliases.txt")

    # General_Category: the leaf values (Cn included) in GENERAL_CATEGORY's order, as one
    # partition of the code space (GC_RUNS, D2334), and the groups as masks of leaves.
    gc = parse_props(fetch(vendor, "extracted/DerivedGeneralCategory.txt"))
    gc_entries, gc_groups, leaf_sets = [], [], []
    groups = {"C": "Cc,Cf,Cn,Co,Cs", "L": "Ll,Lm,Lo,Lt,Lu", "LC": "Ll,Lt,Lu",
              "M": "Mc,Me,Mn", "N": "Nd,Nl,No", "P": "Pc,Pd,Pe,Pf,Pi,Po,Ps",
              "S": "Sc,Sk,Sm,So", "Z": "Zl,Zp,Zs"}
    aliases = value_aliases(pva, "gc")
    leaf_index = {}
    for names in aliases:
        if names[0] not in groups:
            leaf_index[names[0]] = len(gc_entries)
            gc_entries.append((",".join(names),))
            leaf_sets.append(gc.get(names[0], set()))
    assert len(gc_entries) == 30, len(gc_entries)
    for names in aliases:
        if names[0] in groups:
            mask = sum(1 << leaf_index[m] for m in groups[names[0]].split(","))
            gc_groups.append((",".join(names), mask))
    gc_runs = encode_partition(leaf_sets)

    # Script and Script_Extensions. scx(X) = sc(X) - EXPLICIT + explicit(X), where
    # EXPLICIT is every code point listed in ScriptExtensions.txt.
    sc = parse_props(fetch(vendor, "Scripts.txt"))
    explicit = {}
    path = fetch(vendor, "ScriptExtensions.txt")
    check_version(path)
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            fields = [x.strip() for x in line.split(";")]
            lo, _, hi = fields[0].partition("..")
            lo = int(lo, 16)
            hi = int(hi, 16) if hi else lo
            for name in fields[1].split():
                explicit.setdefault(name, set()).update(range(lo, hi + 1))
    all_explicit = set().union(*explicit.values())
    assigned_sc = set().union(*sc.values())
    scripts = []
    for names in value_aliases(pva, "sc"):
        short, long_ = names[0], names[1]
        cps = sc.get(long_, set())
        if short == "Zzzz":
            cps = set(range(0x110000)) - assigned_sc
        sc_off = encode_set(cps, data)
        scx_off = encode_set(explicit[short], data) if short in explicit else 0xFFFFFFFF
        scripts.append((",".join(names), sc_off, scx_off))
    explicit_off = encode_set(all_explicit, data)

    # Binary properties.
    props = {}
    for name in ["PropList.txt", "DerivedCoreProperties.txt",
                 "extracted/DerivedBinaryProperties.txt", "DerivedNormalizationProps.txt"]:
        for k, v in parse_props(fetch(vendor, name)).items():
            props.setdefault(k, set()).update(v)
    emoji = parse_props(fetch(vendor, "emoji/emoji-data.txt"), "Version: 17.0")
    for k, v in emoji.items():
        props.setdefault(k, set()).update(v)
    # Each binary property is coded as a base (a union of General_Category leaves and at
    # most one earlier binary property) and its symmetric difference from the property,
    # whichever is smallest (D2334). Most are close to a union of leaves (ID_Start: the
    # letters and Nl) or to another property (XID_Start: ID_Start).
    binary, done = [], []
    for name, alias in BINARY_PROPERTIES:
        names = name if alias is None else f"{name},{alias}"
        target = props[name]
        best = None
        for j in [None] + list(range(len(done))):
            base = set() if j is None else done[j]
            for use_gc in (False, True):
                mask, full = gc_mask_toward(target, base, leaf_sets) if use_gc else (0, set(base))
                cand = []
                varint(mask, cand)
                varint(0 if j is None else j + 1, cand)
                encode_set(target ^ full, cand)
                if best is None or len(cand) < len(best):
                    best = cand
        binary.append((names, len(data)))
        data.extend(best)
        done.append(target)

    # Properties of strings.
    seqs = {}
    for name in ["emoji-sequences.txt", "emoji-zwj-sequences.txt"]:
        path = fetch(vendor, f"emoji-seq/{name}", f"{EMOJI_URL}/{name}")
        with open(path, encoding="utf-8") as f:
            text = f.read()
        if "Version: 17.0" not in text[:2000]:
            sys.exit(f"{path}: expected Version: 17.0")
        for line in text.split("\n"):
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            fields = [x.strip() for x in line.split(";")]
            entry = seqs.setdefault(fields[1], ([], []))
            if ".." in fields[0]:
                lo, hi = fields[0].split("..")
                entry[0].extend(range(int(lo, 16), int(hi, 16) + 1))
            else:
                cps = [int(x, 16) for x in fields[0].split()]
                if len(cps) == 1:
                    entry[0].append(cps[0])
                else:
                    entry[1].append(cps)
    # Sequences coded by their structure where it has one (D2334, as libunicode does):
    # kind 0 front-coded sequences, 1 `c FE0F` pairs as the set of c, 2 `c modifier` pairs
    # with all five skin tones as the set of c, 3 flag pairs of regional indicators as the
    # set of (first - 1F1E6) * 26 + (second - 1F1E6), 4 ZWJ sequences as templates (see
    # encode_zwj).
    strings = []
    for name in STRING_PROPERTIES:
        chars, multi = seqs[name]
        kind = STRING_KINDS[name]
        if kind == 1:
            assert all(len(q) == 2 and q[1] == 0xFE0F for q in multi), name
            seq_off = encode_set({q[0] for q in multi}, data)
        elif kind == 2:
            heads = {q[0] for q in multi}
            assert {tuple(q) for q in multi} == {(h, m) for h in heads for m in MODIFIERS}, name
            seq_off = encode_set(heads, data)
        elif kind == 3:
            ri = range(0x1F1E6, 0x1F200)
            assert all(len(q) == 2 and q[0] in ri and q[1] in ri for q in multi), name
            seq_off = encode_set({(q[0] - 0x1F1E6) * 26 + (q[1] - 0x1F1E6) for q in multi}, data)
        elif kind == 4:
            seq_off = len(data)
            data.extend(encode_zwj(multi))
        else:
            seq_off = encode_sequences(multi, data)
        strings.append((name, encode_set(set(chars), data), seq_off, kind))

    def tuples(name, doc, ty, rows):
        lines = [f"/// {doc}", f"pub(super) static {name}: [{ty}; {len(rows)}] = ["]
        for row in rows:
            cells = ", ".join(f'"{x}"' if isinstance(x, str) else str(x) for x in row)
            lines.append(f"    ({cells}),")
        lines.append("];")
        return "\n".join(lines)

    blob = ["/// The encoded sets and sequences (see the module docs).",
            f"pub(super) static DATA: [u8; {len(data)}] = ["]
    for i in range(0, len(data), 24):
        blob.append("    " + " ".join(f"{b}," for b in data[i:i + 24]))
    blob.append("];")
    parts = [
        "// Generated by scripts/gen-unicode.py from the Unicode Character Database. Do not edit.",
        "//",
        "// Sets in DATA are varints (7 bits per byte, low first): the number of ranges, then",
        "// per range the gap from the previous range's end + 1 and the length - 1. Sequence",
        "// lists are sorted and front-coded: the count, then per sequence the length of the",
        "// prefix shared with the previous one, the number of new code points, and those as",
        "// zigzag deltas from the code point before each. Names are comma-separated aliases.",
        "// Binary properties, General_Category and the emoji sequences have their own codings",
        "// (D2334, see the tables' docs and scripts/gen-unicode.py).",
        "",
        "/// General_Category leaf values: names; the index is the value in GC_RUNS and the",
        "/// bit in masks.",
        f"pub(super) static GENERAL_CATEGORY: [&str; {len(gc_entries)}] = [",
        *[f'    "{e[0]}",' for e in gc_entries],
        "];",
        "",
        tuples("GENERAL_CATEGORY_GROUPS", "General_Category groups: names, mask of leaf values.",
               "(&str, u32)", gc_groups),
        "",
        "/// General_Category as a partition of the code space: runs from 0, each a byte",
        "/// `len << 5 | value` for lengths 1..=6, or `7 << 5 | value` and a varint length - 7.",
        f"pub(super) static GC_RUNS: [u8; {len(gc_runs)}] = [",
        *["    " + " ".join(f"{b}," for b in gc_runs[i:i + 24]) for i in range(0, len(gc_runs), 24)],
        "];",
        "",
        tuples("SCRIPTS", "Script values: names, Script set, Script_Extensions additions "
               "(u32::MAX: none).", "(&str, u32, u32)", scripts),
        "",
        "/// Every code point listed in ScriptExtensions.txt.",
        f"pub(super) const SCX_EXPLICIT: u32 = {explicit_off};",
        "",
        tuples("BINARY", "Binary properties: names, coded set (varint mask of General_Category "
               "leaves, varint index + 1 of an earlier property or 0, then the set to XOR with "
               "their union).", "(&str, u32)", binary),
        "",
        tuples("STRINGS", "Properties of strings: name, single code points, sequences, kind of "
               "the sequences' coding (see gen-unicode.py).", "(&str, u32, u32, u8)", strings),
        "",
        "\n".join(blob),
        "",
    ]
    return "\n".join(parts)


# ---- Normalization (norm_tables.rs, D1760) ----------------------------------------------

NORM_OUT = os.path.join(ROOT, "crates/djs-core/src/unicode/norm_tables.rs")
NORM_INDEX_STEP = 32


def generate_norm(vendor):
    path = fetch(vendor, "UnicodeData.txt")
    ccc = {}
    decomp = {}  # cp -> (compat, [cps])
    with open(path, encoding="utf-8") as f:
        for line in f:
            fields = line.split(";")
            cp = int(fields[0], 16)
            if int(fields[3]):
                ccc[cp] = int(fields[3])
            d = fields[5]
            if d:
                parts = d.split()
                compat = parts[0].startswith("<")
                if compat:
                    parts = parts[1:]
                decomp[cp] = (compat, [int(p, 16) for p in parts])
    props = parse_props(fetch(vendor, "DerivedNormalizationProps.txt"))
    excl = props["Full_Composition_Exclusion"]
    # Not used here: the conformance file read by normalize.rs's unit test.
    fetch(vendor, "NormalizationTest.txt")

    # QC values: a range list of code points with NO, and one with MAYBE.
    qc = {}
    path = fetch(vendor, "DerivedNormalizationProps.txt")
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            fields = [x.strip() for x in line.split(";")]
            if fields[1] in ("NFC_QC", "NFD_QC", "NFKC_QC", "NFKD_QC"):
                lo, _, hi = fields[0].partition("..")
                lo = int(lo, 16)
                hi = int(hi, 16) if hi else lo
                qc.setdefault((fields[1], fields[2]), set()).update(range(lo, hi + 1))

    # CCC runs: start << 11 | (len - 1), value per run.
    runs = []
    for c in sorted(ccc):
        if runs and runs[-1][0] + runs[-1][1] == c and runs[-1][2] == ccc[c] and runs[-1][1] < MAX_LEN:
            runs[-1][1] += 1
        else:
            runs.append([c, 1, ccc[c]])
    ccc_keys = [(s << LEN_BITS) | (n - 1) for s, n, _ in runs]
    ccc_vals = [v for _, _, v in runs]

    # Decompositions (single level, as in UnicodeData), as two varint streams of entries
    # sorted by code point (D2337): ENTRIES has per entry the gap from the previous entry's
    # last code point (0 at an index point) and a header `len << 1 | compat` (len 0 is a
    # run: a count n follows, and the n + 1 code points from the entry's on map to one code
    # point each, consecutive from the first); TARGETS has the mapped code points as
    # zigzag deltas. The first is predicted by the previous entry's first mapped code point
    # (by the entry's own code point at an index point), the k-th by the previous entry's
    # k-th if it had one (so `A + U+0300`, `A + U+0301` cost a byte each), else by the
    # code point before it. Every NORM_INDEX_STEP entries the index records the code point
    # and both stream offsets, and the predictions restart.
    entries, targets = [], []
    index = []
    keys = sorted(decomp)
    prev_cp = 0
    prev_m = []
    i = 0
    n = 0
    while i < len(keys):
        cp = keys[i]
        compat, m = decomp[cp]
        j = i
        while (
            j + 1 < len(keys)
            and keys[j + 1] == keys[j] + 1
            and len(decomp[keys[j]][1]) == 1
            and len(decomp[keys[j + 1]][1]) == 1
            and decomp[keys[j + 1]][1][0] == decomp[keys[j]][1][0] + 1
            and decomp[keys[j + 1]][0] == compat
        ):
            j += 1
        if n % NORM_INDEX_STEP == 0:
            index.append((cp, len(entries), len(targets)))
            varint(0, entries)
            prev_m = [cp]
        else:
            varint(cp - prev_cp, entries)
        varint((0 if j > i else len(m)) << 1 | (1 if compat else 0), entries)
        if j > i:
            varint(j - i, entries)
        last = None
        for k, c in enumerate(m):
            pred = prev_m[k] if k < len(prev_m) else last
            varint(zigzag(c - pred), targets)
            last = c
        prev_m = m
        prev_cp = keys[j]
        i = j + 1
        n += 1
    assert len(entries) < 1 << 16 and len(targets) < 1 << 16

    # Primary composites are derived at run time from the canonical pairs (D2338): a pair
    # composes unless it is a non-starter decomposition (the composite or its first code
    # point has a nonzero combining class) or is listed in COMPOSE_EXCLUDED (the rest of
    # Full_Composition_Exclusion: CompositionExclusions.txt's script-specific and
    # post-composition-version entries).
    pairs = {cp for cp, (compat, m) in decomp.items() if not compat and len(m) == 2}
    nonstarter = {cp for cp in pairs if ccc.get(cp, 0) or ccc.get(decomp[cp][1][0], 0)}
    explicit = sorted(cp for cp in pairs & excl if cp not in nonstarter)
    composing = pairs - excl
    assert composing == pairs - nonstarter - set(explicit)
    # normalize.rs: decode buffers of 18 code points, and its early exit for seconds below
    # U+0300.
    assert max(len(m) for _, m in decomp.values()) <= 18
    assert min(decomp[cp][1][1] for cp in composing) >= 0x300

    def u32s(name, doc, words):
        return emit_table(name, doc, words)

    def plain(name, doc, ty, values, per=12):
        lines = [f"/// {doc}", f"pub(super) static {name}: [{ty}; {len(values)}] = ["]
        for i in range(0, len(values), per):
            lines.append("    " + " ".join(f"{v}," for v in values[i:i + per]))
        lines.append("];")
        return "\n".join(lines)

    parts = [
        "// Generated by scripts/gen-unicode.py from the Unicode Character Database. Do not edit.",
        "//",
        "// Normalization data (D1760). Range tables use the packing of tables.rs (all code",
        "// points, not only >= 0x80). DECOMP_* are varint streams (see the script).",
        "",
        f"pub(super) const INDEX_STEP: usize = {NORM_INDEX_STEP};",
        "",
        u32s("CCC_RUNS", "Runs of equal nonzero Canonical_Combining_Class.", ccc_keys),
        "",
        plain("CCC_VALUES", "The class of each CCC_RUNS run.", "u8", ccc_vals, 24),
        "",
        plain("DECOMP_ENTRIES", "Decomposition entries: gaps, headers, run counts (varints).",
              "u8", entries, 24),
        "",
        plain("DECOMP_TARGETS", "Decomposition mappings: predicted zigzag deltas (varints).",
              "u8", targets, 24),
        "",
        plain("DECOMP_INDEX", "Every INDEX_STEP-th entry: (code point, offset in DECOMP_ENTRIES, "
              "offset in DECOMP_TARGETS).", "(u32, u16, u16)",
              [f"(0x{c:x}, {e}, {t})" for c, e, t in index], 5),
        "",
        plain("COMPOSE_EXCLUDED", "Canonical pairs that do not compose, besides the non-starter "
              "decompositions.", "u32", [f"0x{c:x}" for c in explicit], 10),
        "",
    ]
    # Only NFC's quick-check tables (localeCompare's hot path). The other forms' quick
    # checks follow from the decompositions (D2335): NFD_QC=No is "has a canonical
    # decomposition", NFKD_QC=No "has any", and NFKC_QC=No/Maybe is NFC's plus "the full
    # compatibility decomposition differs from the canonical one". Checked here.
    hangul = set(range(0xAC00, 0xAC00 + 11172))

    def full(c, compat):
        if c in decomp and (compat or not decomp[c][0]):
            return [x for y in decomp[c][1] for x in full(y, compat)]
        return [c]

    assert qc[("NFD_QC", "N")] == {c for c, (k, _) in decomp.items() if not k} | hangul
    assert qc[("NFKD_QC", "N")] == set(decomp) | hangul
    assert qc[("NFKC_QC", "M")] == qc[("NFC_QC", "M")]
    assert qc[("NFKC_QC", "N")] | qc[("NFKC_QC", "M")] == (
        qc[("NFC_QC", "N")] | qc[("NFC_QC", "M")]
        | {c for c in decomp if full(c, True) != full(c, False)})
    for name, prop, val, doc in [
        ("NFC_QC_NO", "NFC_QC", "N", "NFC_QC = No."),
        ("NFC_QC_MAYBE", "NFC_QC", "M", "NFC_QC = Maybe."),
    ]:
        parts.append(u32s(name, doc, packed(qc.get((prop, val), set()))))
        parts.append("")
    return "\n".join(parts)


def main():
    vendor = os.path.join(primary_checkout(), "vendor", "unicode", UNICODE_VERSION)
    outputs = [
        (OUT, generate(vendor)),
        (CASE_OUT, generate_case(vendor)),
        (PROPS_OUT, generate_props(vendor)),
        (NORM_OUT, generate_norm(vendor)),
    ]
    if "--check" in sys.argv[1:]:
        for path, text in outputs:
            try:
                with open(path, encoding="utf-8") as f:
                    current = f.read()
            except FileNotFoundError:
                current = None
            if current != text:
                sys.exit(f"{path} is out of date; run scripts/gen-unicode.py")
        return
    for path, text in outputs:
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"wrote {os.path.relpath(path, ROOT)}")


if __name__ == "__main__":
    main()
