// Promise: the constructor, then/catch/finally, the statics, and job order.
console.log("start");
Promise.resolve(1).then(v => console.log("then", v));
new Promise((res) => res(2)).then(v => { console.log("ctor", v); return v * 2; }).then(v => console.log("chain", v));
Promise.reject(new Error("bad")).catch(e => console.log("caught", e.message)).finally(() => console.log("finally"));
Promise.all([1, Promise.resolve(2), { then(r) { r(3); } }]).then(v => console.log("all", v));
Promise.all([]).then(v => console.log("all empty", v));
Promise.all([1, Promise.reject(new TypeError("no"))]).catch(e => console.log("all rejected", e));
Promise.allSettled([1, Promise.reject(2)]).then(v => console.log("allSettled", v));
Promise.any([Promise.reject(1), Promise.resolve(5)]).then(v => console.log("any", v));
Promise.any([Promise.reject(1), Promise.reject(2)]).catch(e => console.log("any rejected", e.name, e.errors, e.message === ""));
Promise.race([new Promise(() => {}), Promise.resolve(7)]).then(v => console.log("race", v));
const wr = Promise.withResolvers();
wr.promise.then(v => console.log("withResolvers", v));
wr.resolve(9);
wr.resolve(10);
wr.reject(11);
Promise.try(() => 10).then(v => console.log("try", v));
Promise.try((a, b) => { throw a + b; }, 5, 6).catch(v => console.log("try rejected", v));
Promise.resolve(1).then(2, 3).then(v => console.log("passthrough", v));
Promise.reject(4).then(undefined, undefined).catch(v => console.log("passthrough rejected", v));
Promise.resolve(5).finally(() => 6).then(v => console.log("finally keeps", v));
Promise.reject(7).finally(() => {}).catch(v => console.log("finally keeps reason", v));
Promise.resolve(8).finally(() => { throw 9; }).catch(v => console.log("finally throws", v));
console.log(Object.prototype.toString.call(wr.promise), typeof wr.resolve, wr.resolve.length, "<" + wr.resolve.name + ">");
console.log(Object.getOwnPropertyNames(wr.resolve), Promise.length, Promise.name, Promise[Symbol.species] === Promise);
console.log(Object.getOwnPropertyNames(Promise.prototype).sort(), Promise.prototype[Symbol.toStringTag]);
console.log(Object.getPrototypeOf(wr.promise) === Promise.prototype, wr.promise instanceof Promise);
console.log("end");
