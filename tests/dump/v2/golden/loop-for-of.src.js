// for-of over an array, a Map and a generator: the iterator records in flight.
function* gen() { yield "g1"; yield "g2"; }
async function main() {
  const out = [];
  for (const x of [1, 2]) out.push(await later(x));
  for (const [k, v] of new Map([["a", 1], ["b", 2]])) out.push(k + (await later(v)));
  for (const g of gen()) out.push(await later(g));
  print(out.join());
}
main();
